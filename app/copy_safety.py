def safe_display_text(value: object, fallback: str = "") -> str:
    text = str(value if value is not None else fallback).strip()
    if not text:
        return fallback
    for source, target in TEXT_REPLACEMENTS:
        text = text.replace(source, target)
    return text


def safe_wish_label(value: object) -> str:
    text = str(value or "").strip()
    return SAFE_WISH_LABELS.get(text, safe_display_text(text))
